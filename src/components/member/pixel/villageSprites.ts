const DETAIL_SIZE = 48

function detail(grid: PixelGrid): PixelGrid {
  return upscaleGrid(grid, DETAIL_SIZE)
}

export const VILLAGE_BUILDING_SPRITES: Record<string, PixelGrid> = {
  slg_warehouse: detail(BASE_WAREHOUSE),
  slg_bench: detail(BASE_BENCH),
  slg_plaza: detail(BASE_PLAZA),
  slg_fountain: detail(BASE_FOUNTAIN),
}

export function resolveVillageTreeSprite(stageKey: string): PixelGrid {
  const base = TREE_STAGES[stageKey] ?? TREE_STAGES.seed
  return upscaleGrid(base, DETAIL_SIZE)
}

export function resolveBuildingSprite(spriteKey: string): PixelGrid | null {
  return VILLAGE_BUILDING_SPRITES[spriteKey] ?? null
}
