const TREE_BY_STAGE: Record<string, PixelGrid> = {
  none: TREE_SEED,
  seed: TREE_SEED,
  sprout: TREE_SPROUT,
  small: TREE_SPROUT,
  large: TREE_LARGE,
  sakura: TREE_SAKURA,
}

export function resolveVillageTreeSprite(stageKey: string): PixelGrid {
  return TREE_BY_STAGE[stageKey] ?? TREE_SPROUT
}

export function resolveBuildingSprite(spriteKey: string): PixelGrid | null {
  return VILLAGE_BUILDING_SPRITES[spriteKey] ?? null
}
