type Props = {
  spriteKey: string
  scale?: 1 | 2 | 3
  className?: string
  title?: string
  withShadow?: boolean
}

export function SlgVillagePixelSprite({
  spriteKey,
  scale = 2,
  className = '',
  title,
  withShadow = true,
}: Props) {
  const def = SPRITES[spriteKey] ?? SPRITES.slg_path
  const pixelSize = scale
  const width = def.size * pixelSize
  const height = def.size * pixelSize

  const cells: Array<{ x: number; y: number; color: string }> = []
  for (let y = 0; y < def.pixels.length; y += 1) {
    const row = def.pixels[y] ?? ''
    for (let x = 0; x < row.length; x += 1) {
      const idx = Number(row[x])
      if (!idx) continue
      const color = def.palette[idx]
      if (!color) continue
      cells.push({ x, y, color })
    }
  }

  return (
    <svg
      width={width}
      height={height}
      viewBox={`0 0 ${width} ${height}`}
      className={className}
      role="img"
      aria-label={title ?? spriteKey}
      style={{
        imageRendering: 'pixelated',
        filter: withShadow ? 'drop-shadow(0 1px 1px rgba(0,0,0,0.22))' : undefined,
      }}
    >
      {cells.map((cell) => (
        <rect
          key={`${cell.x}-${cell.y}`}
          x={cell.x * pixelSize}
          y={cell.y * pixelSize}
          width={pixelSize}
          height={pixelSize}
          fill={cell.color}
        />
      ))}
    </svg>
  )
}
